create unique index if not exists leads_submission_id_unique
  on public.leads (submission_id)
  where submission_id is not null;

create unique index if not exists leads_import_key_unique
  on public.leads (import_key)
  where import_key is not null;

create index if not exists leads_team_created_at_idx
  on public.leads (team, created_at desc);

